-- Resident Training & Assessment v1.0.69
-- Prior Experience owner control + exactly two intervention assessors + 48h pending-request reminders.
-- Incremental migration after v1.0.68.

begin;

-- =============================================================================
-- 1) PRIOR EXPERIENCE: exactly two named assessors per scope.
-- =============================================================================
create table if not exists public.prior_experience_scope_assessor_pairs (
  scope_name text primary key,
  junior_assessor_id uuid not null references public.profiles(id),
  senior_assessor_id uuid not null references public.profiles(id),
  assigned_by uuid references public.profiles(id),
  updated_at timestamptz not null default now(),
  constraint prior_experience_pair_distinct_check check (junior_assessor_id <> senior_assessor_id)
);

create table if not exists public.prior_experience_scope_verifications (
  id bigint generated by default as identity primary key,
  logbook_id bigint not null references public.prior_experience_logbooks(id) on delete cascade,
  scope_name text not null,
  assessor_level text not null,
  assessor_id uuid not null references public.profiles(id),
  status text not null default 'pending',
  note text,
  decided_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(logbook_id, scope_name, assessor_level),
  constraint prior_experience_scope_verification_level_check check (assessor_level in ('junior','senior')),
  constraint prior_experience_scope_verification_status_check check (status in ('pending','approved','rejected'))
);

create index if not exists prior_experience_scope_verifications_queue_idx
  on public.prior_experience_scope_verifications(assessor_id,status,created_at);

alter table public.prior_experience_scope_assessor_pairs enable row level security;
alter table public.prior_experience_scope_verifications enable row level security;
revoke all on public.prior_experience_scope_assessor_pairs from public, anon, authenticated;
revoke all on public.prior_experience_scope_verifications from public, anon, authenticated;

-- Reconsiderations now point either to one senior signature or one exact assessor signature.
alter table public.prior_experience_reconsiderations
  drop constraint if exists prior_experience_reconsideration_kind_check;
alter table public.prior_experience_reconsiderations
  add constraint prior_experience_reconsideration_kind_check
  check (review_kind in ('senior','assessor','scope_verification'));

-- Link Prior Experience request messages to their exact pending decision. Used
-- by the 48-hour reminder system so the reminder updates the same request/thread.
create table if not exists public.prior_experience_request_message_links_v1069 (
  message_id bigint primary key references public.private_messages(id) on delete cascade,
  request_kind text not null,
  review_id bigint not null,
  created_at timestamptz not null default now(),
  unique(request_kind,review_id)
);
alter table public.prior_experience_request_message_links_v1069 enable row level security;
revoke all on public.prior_experience_request_message_links_v1069 from public, anon, authenticated;

-- Automatically link future senior-verification messages created by the existing
-- v1.0.68 submit RPC to the exact pending senior signature.
create or replace function public._link_prior_senior_message_v1069()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
declare v_review_id bigint;
begin
  if new.subject='Prior experience senior verification' then
    select sr.id into v_review_id
    from public.prior_experience_senior_reviews sr
    where sr.senior_id=new.receiver_id and sr.status='pending'
      and sr.created_at between new.created_at-interval '10 minutes' and new.created_at+interval '2 minutes'
    order by abs(extract(epoch from (sr.created_at-new.created_at)))
    limit 1;
    if v_review_id is not null then
      insert into public.prior_experience_request_message_links_v1069(message_id,request_kind,review_id)
      values(new.id,'senior',v_review_id)
      on conflict(request_kind,review_id) do nothing;
    end if;
  end if;
  return new;
end;
$$;
drop trigger if exists link_prior_senior_message_v1069 on public.private_messages;
create trigger link_prior_senior_message_v1069 after insert on public.private_messages
for each row execute function public._link_prior_senior_message_v1069();

-- Backfill existing senior request messages where possible.
insert into public.prior_experience_request_message_links_v1069(message_id,request_kind,review_id)
select distinct on (sr.id) pm.id, 'senior', sr.id
from public.prior_experience_senior_reviews sr
join public.prior_experience_logbooks l on l.id=sr.logbook_id
join public.private_messages pm
  on pm.receiver_id=sr.senior_id
 and pm.subject='Prior experience senior verification'
 and pm.created_at between sr.created_at - interval '2 minutes' and sr.created_at + interval '10 minutes'
order by sr.id, abs(extract(epoch from (pm.created_at-sr.created_at)))
on conflict (request_kind,review_id) do nothing;

-- Helper: the scopes actually present in one Prior Experience submission.
create or replace function public._prior_experience_scope_names_v1069(p_logbook_id bigint)
returns table(scope_name text)
language sql
stable
security definer
set search_path=public
as $$
  select distinct i.intervention_name
  from public.prior_experience_interventions i
  where i.logbook_id=p_logbook_id
    and (i.attended_count+i.assisted_count+i.solo_guided_count+i.solo_unguided_count)>0
  union
  select 'Conferences'
  where exists(select 1 from public.prior_experience_conferences c where c.logbook_id=p_logbook_id);
$$;
revoke all on function public._prior_experience_scope_names_v1069(bigint) from public,anon,authenticated;

-- Create/update the two pending signatures for every scope. Completed signatures
-- are never reassigned when Owner later edits the supervision matrix.
create or replace function public._prior_experience_sync_verifications_v1069(p_logbook_id bigint)
returns void
language plpgsql
security definer
set search_path=public
as $$
declare
  v_scope text;
  v_pair public.prior_experience_scope_assessor_pairs%rowtype;
  v_verification_id bigint;
  v_resident uuid;
  v_resident_name text;
  v_owner uuid;
  v_message_id bigint;
begin
  select l.resident_id,rp.display_name into v_resident,v_resident_name
  from public.prior_experience_logbooks l join public.profiles rp on rp.id=l.resident_id
  where l.id=p_logbook_id;
  if v_resident is null then return; end if;

  select p.id into v_owner from public.profiles p
  where p.role::text='owner' and p.is_active=true order by p.created_at nulls last limit 1;

  for v_scope in select s.scope_name from public._prior_experience_scope_names_v1069(p_logbook_id) s
  loop
    select * into v_pair from public.prior_experience_scope_assessor_pairs p where p.scope_name=v_scope;
    if not found then continue; end if;

    -- Junior signature.
    insert into public.prior_experience_scope_verifications(logbook_id,scope_name,assessor_level,assessor_id)
    values(p_logbook_id,v_scope,'junior',v_pair.junior_assessor_id)
    on conflict(logbook_id,scope_name,assessor_level) do update
      set assessor_id=case when prior_experience_scope_verifications.status='pending' then excluded.assessor_id else prior_experience_scope_verifications.assessor_id end,
          updated_at=now()
    returning id into v_verification_id;

    if exists(select 1 from public.prior_experience_scope_verifications v where v.id=v_verification_id and v.status='pending')
       and not exists(select 1 from public.prior_experience_request_message_links_v1069 l where l.request_kind='scope_verification' and l.review_id=v_verification_id) then
      insert into public.private_messages(sender_id,receiver_id,subject,body)
      values(coalesce(v_owner,v_resident),v_pair.junior_assessor_id,'Prior experience verification request',
             'Prior Experience verification · '||v_scope||E'\nResident: '||coalesce(v_resident_name,'Resident')||E'\nRole: Junior assessor signature\nBoth the junior and senior assessor signatures are required.')
      returning id into v_message_id;
      insert into public.prior_experience_request_message_links_v1069(message_id,request_kind,review_id)
      values(v_message_id,'scope_verification',v_verification_id)
      on conflict(request_kind,review_id) do nothing;
    end if;

    -- Senior/older signature.
    insert into public.prior_experience_scope_verifications(logbook_id,scope_name,assessor_level,assessor_id)
    values(p_logbook_id,v_scope,'senior',v_pair.senior_assessor_id)
    on conflict(logbook_id,scope_name,assessor_level) do update
      set assessor_id=case when prior_experience_scope_verifications.status='pending' then excluded.assessor_id else prior_experience_scope_verifications.assessor_id end,
          updated_at=now()
    returning id into v_verification_id;

    if exists(select 1 from public.prior_experience_scope_verifications v where v.id=v_verification_id and v.status='pending')
       and not exists(select 1 from public.prior_experience_request_message_links_v1069 l where l.request_kind='scope_verification' and l.review_id=v_verification_id) then
      insert into public.private_messages(sender_id,receiver_id,subject,body)
      values(coalesce(v_owner,v_resident),v_pair.senior_assessor_id,'Prior experience verification request',
             'Prior Experience verification · '||v_scope||E'\nResident: '||coalesce(v_resident_name,'Resident')||E'\nRole: Senior assessor signature\nBoth the junior and senior assessor signatures are required.')
      returning id into v_message_id;
      insert into public.prior_experience_request_message_links_v1069(message_id,request_kind,review_id)
      values(v_message_id,'scope_verification',v_verification_id)
      on conflict(request_kind,review_id) do nothing;
    end if;
  end loop;
end;
$$;
revoke all on function public._prior_experience_sync_verifications_v1069(bigint) from public,anon,authenticated;

create or replace function public._prior_experience_recalculate_v1069(p_logbook_id bigint)
returns text
language plpgsql
security definer
set search_path=public
as $$
declare
  v_senior_total int;
  v_senior_approved int;
  v_senior_rejected int;
  v_scope_total int;
  v_ver_total int;
  v_ver_approved int;
  v_ver_rejected int;
  v_status text;
begin
  select count(*),count(*) filter(where status='approved'),count(*) filter(where status='rejected')
  into v_senior_total,v_senior_approved,v_senior_rejected
  from public.prior_experience_senior_reviews where logbook_id=p_logbook_id;

  if v_senior_rejected>0 then
    v_status:='rejected';
  elsif v_senior_total<2 or v_senior_approved<2 then
    v_status:='senior_review';
  else
    perform public._prior_experience_sync_verifications_v1069(p_logbook_id);
    select count(*) into v_scope_total from public._prior_experience_scope_names_v1069(p_logbook_id);
    select count(*),count(*) filter(where status='approved'),count(*) filter(where status='rejected')
      into v_ver_total,v_ver_approved,v_ver_rejected
    from public.prior_experience_scope_verifications v
    where v.logbook_id=p_logbook_id
      and exists(select 1 from public._prior_experience_scope_names_v1069(p_logbook_id) s where s.scope_name=v.scope_name);

    if v_ver_rejected>0 then v_status:='rejected';
    elsif v_scope_total=0 or v_ver_total < v_scope_total*2 or v_ver_approved < v_scope_total*2 then v_status:='assessor_review';
    else v_status:='approved'; end if;
  end if;

  update public.prior_experience_logbooks
  set status=v_status,
      verified_at=case when v_status='approved' then coalesce(verified_at,now()) else null end,
      updated_at=now()
  where id=p_logbook_id;
  return v_status;
end;
$$;
revoke all on function public._prior_experience_recalculate_v1069(bigint) from public,anon,authenticated;

