create or replace function public.process_pending_requests_v1069()
returns integer
language plpgsql
security definer
set search_path=public
as $$
declare
  v_row record; v_count integer:=0; v_owner uuid; v_message_id bigint; v_body text; v_claimed timestamptz;
begin
  select p.id into v_owner from public.profiles p where p.role::text='owner' and p.is_active=true order by p.created_at nulls last limit 1;
  for v_row in select * from public._pending_request_rows_v1069()
  loop
    insert into public.workflow_request_reminder_state_v1069(request_key,original_message_id,last_pending_seen_at)
    values(v_row.request_key,v_row.original_message_id,now())
    on conflict(request_key) do update set original_message_id=coalesce(excluded.original_message_id,workflow_request_reminder_state_v1069.original_message_id),last_pending_seen_at=now();

    if now() >= v_row.issued_at + interval '48 hours' then
      v_claimed:=null;
      update public.workflow_request_reminder_state_v1069
         set reminded_at=now()
       where request_key=v_row.request_key and reminded_at is null
       returning reminded_at into v_claimed;
      if v_claimed is not null then
        v_body:=E'\n\n⏰ Automatic reminder after 48 hours\nThis request is still waiting for your decision. Please open the relevant request and approve/reject it.';
        if v_row.original_message_id is not null then
          update public.private_messages set body=coalesce(body,'')||v_body,read_at=null where id=v_row.original_message_id;
          v_message_id:=v_row.original_message_id;
        else
          insert into public.private_messages(sender_id,receiver_id,subject,body)
          values(coalesce(v_owner,v_row.sender_id),v_row.reviewer_id,'48-hour request reminder',
            'Automatic reminder · '||v_row.topic||E'\nSender: '||v_row.sender_name||E'\nThis request has been waiting for more than 48 hours. Please finalize it.')
          returning id into v_message_id;
        end if;
        update public.workflow_request_reminder_state_v1069 set original_message_id=coalesce(original_message_id,v_message_id) where request_key=v_row.request_key;
        v_count:=v_count+1;
      end if;
    end if;
  end loop;
  return v_count;
end;
$$;
