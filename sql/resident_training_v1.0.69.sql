-- New read model used by resident, assessor and Owner screens.
create or replace function public.get_prior_experience_submission_v1069(p_logbook_id bigint default null)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_uid uuid:=auth.uid(); v_role text; v_logbook_id bigint; v_header jsonb;
begin
  select p.role::text into v_role from public.profiles p where p.id=v_uid and p.is_active=true;
  if v_role is null then raise exception 'Active account required'; end if;
  if p_logbook_id is null then
    if v_role<>'resident' then return null; end if;
    select l.id into v_logbook_id from public.prior_experience_logbooks l where l.resident_id=v_uid;
    if v_logbook_id is null then return null; end if;
  else v_logbook_id:=p_logbook_id; end if;

  if not exists(
    select 1 from public.prior_experience_logbooks l where l.id=v_logbook_id and (
      v_role='owner' or l.resident_id=v_uid or l.senior_1_id=v_uid or l.senior_2_id=v_uid
      or exists(select 1 from public.prior_experience_scope_verifications v where v.logbook_id=l.id and v.assessor_id=v_uid)
      or exists(select 1 from public.prior_experience_reconsiderations r where r.logbook_id=l.id and r.reviewer_id=v_uid)
    )
  ) then raise exception 'You cannot view this Prior Experience Logbook'; end if;

  select jsonb_build_object('id',l.id,'resident_id',l.resident_id,'resident_name',rp.display_name,
    'residency_year',rp.residency_year,'status',l.status,'senior_1_id',l.senior_1_id,'senior_2_id',l.senior_2_id,
    'senior_1_name',s1.display_name,'senior_2_name',s2.display_name,'resident_notes',l.resident_notes,
    'submitted_at',l.submitted_at,'verified_at',l.verified_at,'updated_at',l.updated_at,
    'editable',(l.resident_id=v_uid and l.status='draft'))
  into v_header
  from public.prior_experience_logbooks l join public.profiles rp on rp.id=l.resident_id
  left join public.profiles s1 on s1.id=l.senior_1_id left join public.profiles s2 on s2.id=l.senior_2_id
  where l.id=v_logbook_id;

  return jsonb_build_object(
    'header',v_header,
    'interventions',coalesce((select jsonb_agg(jsonb_build_object('id',i.id,'intervention_name',i.intervention_name,
      'attended_count',i.attended_count,'assisted_count',i.assisted_count,'solo_guided_count',i.solo_guided_count,
      'solo_unguided_count',i.solo_unguided_count,'notes',i.notes) order by i.id)
      from public.prior_experience_interventions i where i.logbook_id=v_logbook_id),'[]'::jsonb),
    'conferences',coalesce((select jsonb_agg(jsonb_build_object('id',c.id,'conference_name',c.conference_name,
      'participation',c.participation,'conference_date',c.conference_date,'notes',c.notes) order by c.id)
      from public.prior_experience_conferences c where c.logbook_id=v_logbook_id),'[]'::jsonb),
    'senior_reviews',coalesce((select jsonb_agg(jsonb_build_object('id',sr.id,'senior_id',sr.senior_id,'senior_name',p.display_name,
      'status',sr.status,'note',sr.note,'decided_at',sr.decided_at) order by sr.id)
      from public.prior_experience_senior_reviews sr join public.profiles p on p.id=sr.senior_id where sr.logbook_id=v_logbook_id),'[]'::jsonb),
    'scope_verifications',coalesce((select jsonb_agg(jsonb_build_object('id',v.id,'scope_name',v.scope_name,
      'assessor_level',v.assessor_level,'assessor_id',v.assessor_id,'assessor_name',p.display_name,'status',v.status,
      'note',v.note,'decided_at',v.decided_at) order by v.scope_name,v.assessor_level)
      from public.prior_experience_scope_verifications v join public.profiles p on p.id=v.assessor_id where v.logbook_id=v_logbook_id),'[]'::jsonb),
    'reconsiderations',coalesce((select jsonb_agg(jsonb_build_object('id',r.id,'review_kind',r.review_kind,'review_id',r.review_id,
      'reviewer_id',r.reviewer_id,'reviewer_name',p.display_name,'scope_name',r.scope_name,'resident_reason',r.resident_reason,
      'status',r.status,'reviewer_note',r.reviewer_note,'created_at',r.created_at,'resolved_at',r.resolved_at) order by r.created_at)
      from public.prior_experience_reconsiderations r join public.profiles p on p.id=r.reviewer_id where r.logbook_id=v_logbook_id),'[]'::jsonb)
  );
end;
$$;
revoke all on function public.get_prior_experience_submission_v1069(bigint) from public,anon;
grant execute on function public.get_prior_experience_submission_v1069(bigint) to authenticated;

create or replace function public.get_prior_experience_review_queue_v1069()
returns table(
  review_kind text,review_id bigint,logbook_id bigint,resident_id uuid,resident_name text,residency_year smallint,
  scope_name text,assessor_level text,review_status text,review_note text,submitted_at timestamptz,
  reconsideration_id bigint,reconsideration_status text,reconsideration_reason text
)
language plpgsql
security definer
set search_path=public
as $$
declare v_role text;
begin
  select p.role::text into v_role from public.profiles p where p.id=auth.uid() and p.is_active=true;
  if v_role is null then raise exception 'Active account required'; end if;

  if v_role='resident' then
    return query
    select 'senior'::text,sr.id,l.id,l.resident_id,rp.display_name,rp.residency_year,'Whole prior logbook'::text,null::text,
      sr.status,sr.note,l.submitted_at,rec.id,rec.status,rec.resident_reason
    from public.prior_experience_senior_reviews sr
    join public.prior_experience_logbooks l on l.id=sr.logbook_id join public.profiles rp on rp.id=l.resident_id
    left join lateral(select r.* from public.prior_experience_reconsiderations r where r.review_kind='senior' and r.review_id=sr.id order by r.created_at desc limit 1) rec on true
    where sr.senior_id=auth.uid() and (sr.status='pending' or rec.status='requested')
    order by l.submitted_at;
  elsif v_role='assessor' then
    return query
    select 'scope_verification'::text,v.id,l.id,l.resident_id,rp.display_name,rp.residency_year,v.scope_name,v.assessor_level,
      v.status,v.note,l.submitted_at,rec.id,rec.status,rec.resident_reason
    from public.prior_experience_scope_verifications v
    join public.prior_experience_logbooks l on l.id=v.logbook_id join public.profiles rp on rp.id=l.resident_id
    left join lateral(select r.* from public.prior_experience_reconsiderations r where r.review_kind='scope_verification' and r.review_id=v.id order by r.created_at desc limit 1) rec on true
    where v.assessor_id=auth.uid() and (v.status='pending' or rec.status='requested')
    order by l.submitted_at,v.scope_name,v.assessor_level;
  else return; end if;
end;
$$;
revoke all on function public.get_prior_experience_review_queue_v1069() from public,anon;
grant execute on function public.get_prior_experience_review_queue_v1069() to authenticated;

create or replace function public.review_prior_experience_v1069(p_review_kind text,p_review_id bigint,p_decision text,p_note text default null)
returns text
language plpgsql
security definer
set search_path=public
as $$
declare
  v_uid uuid:=auth.uid(); v_logbook_id bigint; v_resident uuid; v_scope text; v_level text; v_status text;
  v_name text; v_note text:=nullif(btrim(coalesce(p_note,'')),'');
begin
  if p_decision not in ('approved','rejected') then raise exception 'Decision must be approved or rejected'; end if;
  if p_decision='rejected' and v_note is null then raise exception 'Write a comment before rejecting'; end if;
  select p.display_name into v_name from public.profiles p where p.id=v_uid and p.is_active=true;
  if v_name is null then raise exception 'Active reviewer required'; end if;

  if p_review_kind='senior' then
    select sr.logbook_id,l.resident_id into v_logbook_id,v_resident
    from public.prior_experience_senior_reviews sr join public.prior_experience_logbooks l on l.id=sr.logbook_id
    where sr.id=p_review_id and sr.senior_id=v_uid and sr.status='pending' for update of sr;
    if v_logbook_id is null then raise exception 'Pending senior verification not found'; end if;
    update public.prior_experience_senior_reviews set status=p_decision,note=v_note,decided_at=now(),updated_at=now() where id=p_review_id;
  elsif p_review_kind='scope_verification' then
    select v.logbook_id,l.resident_id,v.scope_name,v.assessor_level into v_logbook_id,v_resident,v_scope,v_level
    from public.prior_experience_scope_verifications v join public.prior_experience_logbooks l on l.id=v.logbook_id
    where v.id=p_review_id and v.assessor_id=v_uid and v.status='pending' for update of v;
    if v_logbook_id is null then raise exception 'Pending assessor signature not found'; end if;
    update public.prior_experience_scope_verifications
    set status=p_decision,note=v_note,decided_at=now(),updated_at=now() where id=p_review_id;
  else raise exception 'Unknown Prior Experience review stage'; end if;

  v_status:=public._prior_experience_recalculate_v1069(v_logbook_id);
  insert into public.private_messages(sender_id,receiver_id,subject,body)
  values(v_uid,v_resident,
    case when p_decision='approved' then 'Prior experience approval' else 'Prior experience rejection' end,
    v_name||' '||p_decision||' your '||case when p_review_kind='senior' then 'senior-verification stage' else coalesce(v_scope,'Prior Experience scope')||' ('||initcap(v_level)||' assessor signature)' end||'.'||
    case when v_note is not null then E'\nComment: '||v_note else '' end||
    case when v_status='approved' then E'\n✓ Your Prior Experience Logbook is now fully verified.' when p_decision='rejected' then E'\nYou may request reconsideration.' else '' end);
  return v_status;
end;
$$;
revoke all on function public.review_prior_experience_v1069(text,bigint,text,text) from public,anon;
grant execute on function public.review_prior_experience_v1069(text,bigint,text,text) to authenticated;

create or replace function public.request_prior_experience_reconsideration_v1069(p_review_kind text,p_review_id bigint,p_reason text)
returns bigint
language plpgsql
security definer
set search_path=public
as $$
declare
  v_uid uuid:=auth.uid(); v_logbook_id bigint; v_reviewer uuid; v_scope text; v_id bigint; v_owner uuid; v_message bigint;
  v_reason text:=nullif(btrim(coalesce(p_reason,'')),'');
begin
  if v_reason is null then raise exception 'Write a reason for reconsideration'; end if;
  if p_review_kind='senior' then
    select sr.logbook_id,sr.senior_id into v_logbook_id,v_reviewer
    from public.prior_experience_senior_reviews sr join public.prior_experience_logbooks l on l.id=sr.logbook_id
    where sr.id=p_review_id and l.resident_id=v_uid and sr.status='rejected';
  elsif p_review_kind='scope_verification' then
    select v.logbook_id,v.assessor_id,v.scope_name into v_logbook_id,v_reviewer,v_scope
    from public.prior_experience_scope_verifications v join public.prior_experience_logbooks l on l.id=v.logbook_id
    where v.id=p_review_id and l.resident_id=v_uid and v.status='rejected';
  else raise exception 'Unknown Prior Experience review stage'; end if;
  if v_logbook_id is null then raise exception 'Rejected decision not found'; end if;
  if exists(select 1 from public.prior_experience_reconsiderations r where r.review_kind=p_review_kind and r.review_id=p_review_id and r.status='requested') then
    raise exception 'A reconsideration request is already waiting for this reviewer';
  end if;
  insert into public.prior_experience_reconsiderations(logbook_id,review_kind,review_id,reviewer_id,scope_name,resident_reason)
  values(v_logbook_id,p_review_kind,p_review_id,v_reviewer,v_scope,v_reason) returning id into v_id;

  insert into public.private_messages(sender_id,receiver_id,subject,body)
  values(v_uid,v_reviewer,'Prior experience reconsideration requested',
    'Prior Experience reconsideration'||case when v_scope is not null then ' · '||v_scope else '' end||E'\nReason: '||v_reason)
