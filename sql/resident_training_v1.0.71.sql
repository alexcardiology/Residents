create or replace function public.get_resident_penalties_for_assessment_v1071(p_resident_id uuid)
returns setof jsonb
language plpgsql
stable
security definer
set search_path=public
as $$
declare v_role text; v_year integer;
begin
  select p.role::text into v_role from public.profiles p where p.id=auth.uid() and p.is_active=true;
  select p.residency_year into v_year from public.profiles p where p.id=p_resident_id and p.role::text='resident';
  if v_year is null then raise exception 'Resident not found'; end if;
  if v_role='owner' then null;
  elsif v_role='assessor' then
    if not exists(select 1 from public.assessor_year_assignments a where a.assessor_id=auth.uid() and a.residency_year=v_year and a.is_active=true) then raise exception 'This resident is not in your assigned assessment cohorts'; end if;
  else raise exception 'Assessment penalty access requires assigned assessor or Owner';
  end if;
  return query select public._penalty_json_v1071(p) from public.resident_penalties p
    where p.resident_id=p_resident_id and p.status in ('approved','appeal_pending','appeal_upheld')
    order by p.created_at desc;
end;
$$;
