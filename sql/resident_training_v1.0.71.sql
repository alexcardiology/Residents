-- ============================================================================
-- 1) CONFIGURABLE PENALTY CATALOGUE
-- ============================================================================
create table if not exists public.penalty_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  sort_order integer not null default 10,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.penalty_problems (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.penalty_categories(id),
  name text not null,
  sort_order integer not null default 10,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(category_id,name)
);

create table if not exists public.penalty_punishments (
  id bigint generated by default as identity primary key,
  name text not null unique,
  sort_order integer not null default 10,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

