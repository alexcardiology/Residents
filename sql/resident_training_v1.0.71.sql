create or replace function public.owner_assign_penalty_appeal_reviewers_v1071(p_penalty_id bigint,p_assessor_1 uuid,p_assessor_2 uuid)
returns void
language plpgsql
security definer
set search_path=public
as $$
declare v public.resident_penalties%rowtype; v_owner uuid; v_target text; aid uuid; aname text;
begin
  perform public._require_owner_v1071();
  if p_assessor_1=p_assessor_2 then raise exception 'Choose two different neutral assessors'; end if;
  select * into v from public.resident_penalties where id=p_penalty_id for update;
  if not found or v.status<>'appeal_pending' then raise exception 'This penalty has no open complaint'; end if;
  if p_assessor_1=v.issued_by or p_assessor_2=v.issued_by then raise exception 'The original penalty issuer cannot act as a neutral assessor'; end if;
  if not exists(select 1 from public.profiles p where p.id=p_assessor_1 and p.role::text='assessor' and p.is_active=true) or
     not exists(select 1 from public.profiles p where p.id=p_assessor_2 and p.role::text='assessor' and p.is_active=true) then
    raise exception 'Both neutral reviewers must be active assessors';
  end if;
  delete from public.penalty_appeal_reviewers where penalty_id=p_penalty_id;
  insert into public.penalty_appeal_reviewers(penalty_id,slot,assessor_id,assigned_by) values(p_penalty_id,1,p_assessor_1,auth.uid()),(p_penalty_id,2,p_assessor_2,auth.uid());
  select p.display_name into v_target from public.profiles p where p.id=v.resident_id;
  v_owner:=auth.uid();
  for aid,aname in select p.id,p.display_name from public.profiles p where p.id in (p_assessor_1,p_assessor_2)
  loop
    insert into public.private_messages(sender_id,receiver_id,subject,body) values(v_owner,aid,'Neutral penalty review assigned',
      'Resident: '||coalesce(v_target,'Resident')||E'\nCategory: '||v.category_label||E'\nProblem: '||v.problem_label||E'\nPunishment: '||v.punishment_label||E'\nComplaint: '||coalesce(v.complaint_text,'—')||E'\nOpen Reviews & penalties to uphold or overturn the penalty.');
  end loop;
end;
$$;
revoke all on function public.owner_assign_penalty_appeal_reviewers_v1071(bigint,uuid,uuid) from public,anon;
grant execute on function public.owner_assign_penalty_appeal_reviewers_v1071(bigint,uuid,uuid) to authenticated;

create or replace function public._recalculate_penalty_appeal_v1071(p_penalty_id bigint)
returns text
language plpgsql
security definer
set search_path=public
as $$
declare v public.resident_penalties%rowtype; v_count integer; v_uphold integer; v_overturn integer; v_final text; v_owner uuid; v_target text; v_issuer text;
begin
  select * into v from public.resident_penalties where id=p_penalty_id for update;
  if not found or v.status<>'appeal_pending' then return coalesce(v.status,'missing'); end if;
  if v.appeal_owner_decision is null then return 'appeal_pending'; end if;
  select count(*) filter(where decision is not null),count(*) filter(where decision='uphold'),count(*) filter(where decision='overturn') into v_count,v_uphold,v_overturn from public.penalty_appeal_reviewers where penalty_id=p_penalty_id;
  if v_count<2 then return 'appeal_pending'; end if;
  if v.appeal_owner_decision='uphold' then v_uphold:=v_uphold+1; else v_overturn:=v_overturn+1; end if;
  v_final:=case when v_uphold>=2 then 'appeal_upheld' else 'appeal_overturned' end;
  update public.resident_penalties set status=v_final,appeal_finalized_at=now(),updated_at=now() where id=p_penalty_id;
  v_owner:=public._owner_id_v1071();
  select p.display_name into v_target from public.profiles p where p.id=v.resident_id;
  select p.display_name into v_issuer from public.profiles p where p.id=v.issued_by;
  insert into public.private_messages(sender_id,receiver_id,subject,body) values(v_owner,v.resident_id,
    case when v_final='appeal_upheld' then 'Penalty complaint decision · penalty upheld' else 'Penalty complaint decision · penalty cancelled' end,
    case when v_final='appeal_upheld' then 'The neutral review panel upheld the penalty.' else 'The neutral review panel overturned the penalty. It is no longer an active disciplinary penalty.' end);
  insert into public.private_messages(sender_id,receiver_id,subject,body) values(v_owner,v.issued_by,
    case when v_final='appeal_upheld' then 'Penalty appeal upheld' else 'Penalty appeal overturned' end,
    'Penalty for '||coalesce(v_target,'Resident')||': '||case when v_final='appeal_upheld' then 'upheld by the appeal panel.' else 'overturned by the appeal panel.' end);
  return v_final;
end;
$$;
revoke all on function public._recalculate_penalty_appeal_v1071(bigint) from public,anon,authenticated;

