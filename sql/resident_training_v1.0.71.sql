create or replace function public._owner_id_v1071()
returns uuid
language sql
stable
security definer
set search_path=public
as $$
  select p.id from public.profiles p
  where p.role::text='owner' and p.is_active=true
  order by p.created_at nulls last limit 1;
$$;
