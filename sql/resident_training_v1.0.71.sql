-- ============================================================================
-- 2) PENALTY + COMPLAINT / APPEAL RECORDS
-- ============================================================================
create table if not exists public.resident_penalties (
  id bigint generated by default as identity primary key,
  resident_id uuid not null references public.profiles(id),
  issued_by uuid not null references public.profiles(id),
  category_id bigint not null references public.penalty_categories(id),
  problem_id bigint not null references public.penalty_problems(id),
  punishment_id bigint not null references public.penalty_punishments(id),
  category_label text not null,
  problem_label text not null,
  punishment_label text not null,
  details text not null,
  status text not null default 'pending_owner',
  owner_decision_note text,
  owner_decided_at timestamptz,
  complaint_text text,
  complained_at timestamptz,
  appeal_owner_decision text,
  appeal_owner_note text,
  appeal_owner_decided_at timestamptz,
  appeal_finalized_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint resident_penalties_status_check check (status in (
    'pending_owner','approved','rejected','appeal_pending','appeal_upheld','appeal_overturned'
  )),
  constraint resident_penalties_appeal_owner_check check (appeal_owner_decision is null or appeal_owner_decision in ('uphold','overturn')),
  constraint resident_penalties_not_self_check check (resident_id <> issued_by)
);

create table if not exists public.penalty_appeal_reviewers (
  penalty_id bigint not null references public.resident_penalties(id) on delete cascade,
  slot smallint not null,
  assessor_id uuid not null references public.profiles(id),
  decision text,
  note text,
  decided_at timestamptz,
  assigned_at timestamptz not null default now(),
  assigned_by uuid references public.profiles(id),
  primary key(penalty_id,slot),
  unique(penalty_id,assessor_id),
  constraint penalty_appeal_reviewers_slot_check check (slot in (1,2)),
  constraint penalty_appeal_reviewers_decision_check check (decision is null or decision in ('uphold','overturn'))
);

create index if not exists resident_penalties_resident_idx on public.resident_penalties(resident_id,status,created_at desc);
create index if not exists resident_penalties_issuer_idx on public.resident_penalties(issued_by,created_at desc);
create index if not exists penalty_appeal_reviewer_queue_idx on public.penalty_appeal_reviewers(assessor_id,decision,assigned_at);

alter table public.penalty_categories enable row level security;
alter table public.penalty_problems enable row level security;
alter table public.penalty_punishments enable row level security;
alter table public.resident_penalties enable row level security;
alter table public.penalty_appeal_reviewers enable row level security;

revoke all on public.penalty_categories from public,anon,authenticated;
revoke all on public.penalty_problems from public,anon,authenticated;
revoke all on public.penalty_punishments from public,anon,authenticated;
revoke all on public.resident_penalties from public,anon,authenticated;
revoke all on public.penalty_appeal_reviewers from public,anon,authenticated;

