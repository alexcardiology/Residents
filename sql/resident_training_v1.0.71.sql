create or replace function public.owner_save_penalty_option_v1071(
  p_kind text,
  p_id bigint,
  p_name text,
  p_category_id bigint default null,
  p_sort_order integer default 10
)
returns bigint
language plpgsql
security definer
set search_path=public
as $$
declare v_id bigint;
begin
  perform public._require_owner_v1071();
  if char_length(trim(coalesce(p_name,'')))<2 then raise exception 'Name is required'; end if;
  if p_kind='category' then
    if p_id is null then insert into public.penalty_categories(name,sort_order) values(trim(p_name),coalesce(p_sort_order,10)) returning id into v_id;
    else update public.penalty_categories set name=trim(p_name),sort_order=coalesce(p_sort_order,10),is_active=true,updated_at=now() where id=p_id returning id into v_id; end if;
  elsif p_kind='problem' then
    if p_category_id is null or not exists(select 1 from public.penalty_categories c where c.id=p_category_id) then raise exception 'Choose a category'; end if;
    if p_id is null then insert into public.penalty_problems(category_id,name,sort_order) values(p_category_id,trim(p_name),coalesce(p_sort_order,10)) returning id into v_id;
    else update public.penalty_problems set category_id=p_category_id,name=trim(p_name),sort_order=coalesce(p_sort_order,10),is_active=true,updated_at=now() where id=p_id returning id into v_id; end if;
  elsif p_kind='punishment' then
    if p_id is null then insert into public.penalty_punishments(name,sort_order) values(trim(p_name),coalesce(p_sort_order,10)) returning id into v_id;
    else update public.penalty_punishments set name=trim(p_name),sort_order=coalesce(p_sort_order,10),is_active=true,updated_at=now() where id=p_id returning id into v_id; end if;
  else raise exception 'Unknown option type'; end if;
  if v_id is null then raise exception 'Option not found'; end if;
  return v_id;
end;
$$;
