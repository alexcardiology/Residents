create or replace function public._require_owner_v1071()
returns void
language plpgsql
security definer
set search_path=public
as $$
begin
  if not exists(select 1 from public.profiles p where p.id=auth.uid() and p.role::text='owner' and p.is_active=true) then
    raise exception 'Owner access required';
  end if;
end;
$$;
