create or replace function public.get_penalties_for_me_v1071()
returns setof jsonb
language plpgsql
stable
security definer
set search_path=public
as $$
declare v_role text;
begin
  select p.role::text into v_role from public.profiles p where p.id=auth.uid() and p.is_active=true;
  if v_role is null then raise exception 'Active account required'; end if;
  if v_role='owner' then
    return query select public._penalty_json_v1071(p) from public.resident_penalties p order by p.created_at desc;
  elsif v_role='resident' then
    return query select public._penalty_json_v1071(p) from public.resident_penalties p
      where p.issued_by=auth.uid()
         or (p.resident_id=auth.uid() and p.status in ('approved','appeal_pending','appeal_upheld','appeal_overturned'))
      order by p.created_at desc;
  elsif v_role='assessor' then
    return query select public._penalty_json_v1071(p) from public.resident_penalties p
      where p.issued_by=auth.uid() or exists(select 1 from public.penalty_appeal_reviewers ar where ar.penalty_id=p.id and ar.assessor_id=auth.uid())
      order by p.created_at desc;
  else return;
  end if;
end;
$$;
