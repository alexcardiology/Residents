-- ============================================================================
create or replace function public.owner_decide_penalty_v1071(p_penalty_id bigint,p_decision text,p_note text default null)
returns text
language plpgsql
security definer
set search_path=public
as $$
declare v public.resident_penalties%rowtype; v_owner uuid; v_owner_name text; v_target text; v_issuer text;
begin
  perform public._require_owner_v1071();
  if p_decision not in ('approved','rejected') then raise exception 'Decision must be approved or rejected'; end if;
  select * into v from public.resident_penalties where id=p_penalty_id for update;
  if not found then raise exception 'Penalty not found'; end if;
  if v.status<>'pending_owner' then raise exception 'This penalty has already been decided'; end if;
  update public.resident_penalties set status=p_decision,owner_decision_note=nullif(trim(coalesce(p_note,'')),''),owner_decided_at=now(),updated_at=now() where id=p_penalty_id;
  select p.display_name into v_target from public.profiles p where p.id=v.resident_id;
  select p.display_name into v_issuer from public.profiles p where p.id=v.issued_by;
  select p.id,p.display_name into v_owner,v_owner_name from public.profiles p where p.id=auth.uid();
  if p_decision='approved' then
    insert into public.private_messages(sender_id,receiver_id,subject,body) values(v_owner,v.resident_id,'Penalty approved',
      'A penalty was approved by the Program Owner.'||E'\nCategory: '||v.category_label||E'\nProblem: '||v.problem_label||E'\nPunishment: '||v.punishment_label||E'\nDetails: '||v.details||E'\nSigned by: '||coalesce(v_issuer,'Reviewer')||case when nullif(trim(coalesce(p_note,'')),'') is not null then E'\nOwner note: '||trim(p_note) else '' end||E'\nYou may complain from Reviews & penalties.');
    insert into public.private_messages(sender_id,receiver_id,subject,body) values(v_owner,v.issued_by,'Penalty approved by Program Owner','Your penalty for '||coalesce(v_target,'Resident')||' was approved.');
  else
    insert into public.private_messages(sender_id,receiver_id,subject,body) values(v_owner,v.issued_by,'Penalty rejected by Program Owner','Your proposed penalty for '||coalesce(v_target,'Resident')||' was rejected.'||case when nullif(trim(coalesce(p_note,'')),'') is not null then E'\nOwner note: '||trim(p_note) else '' end);
  end if;
  return p_decision;
end;
$$;
revoke all on function public.owner_decide_penalty_v1071(bigint,text,text) from public,anon;
grant execute on function public.owner_decide_penalty_v1071(bigint,text,text) to authenticated;

