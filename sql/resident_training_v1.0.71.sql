create or replace function public.resident_complain_penalty_v1071(p_penalty_id bigint,p_complaint text)
returns void
language plpgsql
security definer
set search_path=public
as $$
declare v public.resident_penalties%rowtype; v_owner uuid; v_name text;
begin
  select * into v from public.resident_penalties where id=p_penalty_id and resident_id=auth.uid() for update;
  if not found then raise exception 'Penalty not found'; end if;
  if v.status<>'approved' then raise exception 'Only an approved penalty can be complained against'; end if;
  if char_length(trim(coalesce(p_complaint,'')))<2 then raise exception 'Write your complaint'; end if;
  update public.resident_penalties set status='appeal_pending',complaint_text=trim(p_complaint),complained_at=now(),appeal_owner_decision=null,appeal_owner_note=null,appeal_owner_decided_at=null,appeal_finalized_at=null,updated_at=now() where id=p_penalty_id;
  delete from public.penalty_appeal_reviewers where penalty_id=p_penalty_id;
  v_owner:=public._owner_id_v1071();
  select p.display_name into v_name from public.profiles p where p.id=auth.uid();
  insert into public.private_messages(sender_id,receiver_id,subject,body) values(auth.uid(),v_owner,'Penalty complaint',
    'Resident: '||coalesce(v_name,'Resident')||E'\nPenalty: '||v.category_label||' · '||v.problem_label||E'\nPunishment: '||v.punishment_label||E'\nComplaint: '||trim(p_complaint)||E'\nChoose two neutral assessors in Reviews & penalties.');
end;
$$;
