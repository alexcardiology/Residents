-- 6) CREATE PENALTY
-- ============================================================================
create or replace function public.create_resident_penalty_v1071(
  p_resident_id uuid,
  p_category_id bigint,
  p_problem_id bigint,
  p_punishment_id bigint,
  p_details text
)
returns bigint
language plpgsql
security definer
set search_path=public
as $$
declare
  v_role text; v_year integer; v_target_year integer; v_id bigint;
  v_category text; v_problem text; v_punishment text; v_owner uuid; v_issuer text; v_target text;
begin
  select p.role::text,p.residency_year,p.display_name into v_role,v_year,v_issuer
  from public.profiles p where p.id=auth.uid() and p.is_active=true;
  if v_role is null then raise exception 'Active account required'; end if;
  select p.residency_year,p.display_name into v_target_year,v_target from public.profiles p
  where p.id=p_resident_id and p.role::text='resident' and p.is_active=true;
  if v_target_year is null then raise exception 'Resident not found'; end if;
  if p_resident_id=auth.uid() then raise exception 'You cannot sign a penalty against yourself'; end if;
  if v_role='resident' then
    if coalesce(v_year,0)<=1 then raise exception 'Year 1 residents cannot sign penalties'; end if;
    if v_target_year >= v_year then raise exception 'Residents may sign penalties only against residents in a lower residency year'; end if;
  elsif v_role<>'assessor' then
    raise exception 'Only eligible senior residents and assessors can sign penalties';
  end if;
  if char_length(trim(coalesce(p_details,'')))<2 then raise exception 'Write a short description of the incident'; end if;

  select c.name into v_category from public.penalty_categories c where c.id=p_category_id and c.is_active=true;
  select x.name into v_problem from public.penalty_problems x where x.id=p_problem_id and x.category_id=p_category_id and x.is_active=true;
  select q.name into v_punishment from public.penalty_punishments q where q.id=p_punishment_id and q.is_active=true;
  if v_category is null or v_problem is null or v_punishment is null then raise exception 'Choose valid active penalty options'; end if;

  insert into public.resident_penalties(resident_id,issued_by,category_id,problem_id,punishment_id,category_label,problem_label,punishment_label,details)
  values(p_resident_id,auth.uid(),p_category_id,p_problem_id,p_punishment_id,v_category,v_problem,v_punishment,trim(p_details))
  returning id into v_id;

  v_owner:=public._owner_id_v1071();
  if v_owner is null then raise exception 'Active Program Owner required'; end if;
  insert into public.private_messages(sender_id,receiver_id,subject,body)
  values(auth.uid(),v_owner,'Penalty awaiting approval',
    'Resident: '||coalesce(v_target,'Resident')||E'\nSigned by: '||coalesce(v_issuer,'Reviewer')||E'\nCategory: '||v_category||E'\nProblem: '||v_problem||E'\nProposed punishment: '||v_punishment||E'\nDetails: '||trim(p_details)||E'\nOpen Reviews & penalties to approve or reject it.');
  return v_id;
end;
$$;
revoke all on function public.create_resident_penalty_v1071(uuid,bigint,bigint,bigint,text) from public,anon;
grant execute on function public.create_resident_penalty_v1071(uuid,bigint,bigint,bigint,text) to authenticated;

