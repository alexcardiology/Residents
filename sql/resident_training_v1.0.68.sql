-- --------------------------------------------------------------
-- Exact rejecting reviewer resolves reconsideration.
-- --------------------------------------------------------------
create or replace function public.resolve_prior_experience_reconsideration_v1068(
  p_reconsideration_id bigint,
  p_decision text,
  p_note text default null
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_rec public.prior_experience_reconsiderations%rowtype;
  v_resident uuid;
  v_status text;
  v_note text := nullif(btrim(coalesce(p_note,'')),'');
begin
  if p_decision not in ('approved','rejected') then raise exception 'Decision must be approved or rejected'; end if;
  if p_decision='rejected' and v_note is null then raise exception 'Write a note when keeping the rejection'; end if;

  select * into v_rec from public.prior_experience_reconsiderations r
  where r.id=p_reconsideration_id and r.reviewer_id=v_uid and r.status='requested'
  for update;
  if not found then raise exception 'Pending reconsideration not found'; end if;

  select l.resident_id into v_resident from public.prior_experience_logbooks l where l.id=v_rec.logbook_id;

  if p_decision='approved' then
    if v_rec.review_kind='senior' then
      update public.prior_experience_senior_reviews
         set status='approved', note=concat_ws(E'\n',nullif(note,''),'Reconsideration approved'||case when v_note is not null then ': '||v_note else '' end), decided_at=now(), updated_at=now()
       where id=v_rec.review_id;
    else
      update public.prior_experience_scope_reviews
         set status='approved', note=concat_ws(E'\n',nullif(note,''),'Reconsideration approved'||case when v_note is not null then ': '||v_note else '' end), decided_at=now(), updated_at=now()
       where id=v_rec.review_id;
    end if;
  end if;

  update public.prior_experience_reconsiderations
     set status=p_decision, reviewer_note=v_note, resolved_at=now()
   where id=v_rec.id;

  v_status := public._prior_experience_recalculate_v1068(v_rec.logbook_id);

  insert into public.private_messages(sender_id,receiver_id,subject,body)
  values (v_uid,v_resident,
    case when p_decision='approved' then 'Prior experience reconsideration approved' else 'Prior experience reconsideration rejected' end,
    case when p_decision='approved' then 'Your prior-experience reconsideration was accepted and the original rejection changed to approval.' else 'Your prior-experience reconsideration was not accepted; the original rejection remains.' end ||
    case when v_note is not null then E'\nReviewer note: '||v_note else '' end ||
    case when v_status='approved' then E'\nYour Prior Experience Logbook is now fully verified.' else '' end
  );

  return v_status;
end;
$$;
revoke all on function public.resolve_prior_experience_reconsideration_v1068(bigint,text,text) from public, anon;
grant execute on function public.resolve_prior_experience_reconsideration_v1068(bigint,text,text) to authenticated;

