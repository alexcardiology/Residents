-- Resident Training & Assessment v1.0.68
-- Prior Experience Logbook
-- - Resident editable draft before final submission
-- - Two senior-resident approvals first
-- - Then intervention-scoped assessor verification
-- - Assessor comments + approve/reject
-- - Reconsideration workflow for senior/assessor rejections
-- - Owner assignment of assessors to intervention scopes

begin;

create table if not exists public.prior_experience_logbooks (
  id bigint generated by default as identity primary key,
  resident_id uuid not null unique references public.profiles(id) on delete cascade,
  status text not null default 'draft',
  senior_1_id uuid references public.profiles(id),
  senior_2_id uuid references public.profiles(id),
  resident_notes text,
  submitted_at timestamptz,
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint prior_experience_logbooks_status_check check (status in ('draft','senior_review','assessor_review','rejected','approved'))
);

create table if not exists public.prior_experience_interventions (
  id bigint generated by default as identity primary key,
  logbook_id bigint not null references public.prior_experience_logbooks(id) on delete cascade,
  intervention_name text not null,
  attended_count integer not null default 0,
  assisted_count integer not null default 0,
  solo_guided_count integer not null default 0,
  solo_unguided_count integer not null default 0,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(logbook_id, intervention_name),
  constraint prior_experience_interventions_counts_check check (
    attended_count >= 0 and assisted_count >= 0 and solo_guided_count >= 0 and solo_unguided_count >= 0
  )
);

create table if not exists public.prior_experience_conferences (
  id bigint generated by default as identity primary key,
  logbook_id bigint not null references public.prior_experience_logbooks(id) on delete cascade,
  conference_name text not null,
  participation text not null,
  conference_date date,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint prior_experience_conferences_participation_check check (participation in ('attended','speaker'))
);

create table if not exists public.prior_experience_senior_reviews (
  id bigint generated by default as identity primary key,
  logbook_id bigint not null references public.prior_experience_logbooks(id) on delete cascade,
  senior_id uuid not null references public.profiles(id),
  status text not null default 'pending',
  note text,
  decided_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(logbook_id, senior_id),
  constraint prior_experience_senior_status_check check (status in ('pending','approved','rejected'))
);

create table if not exists public.prior_experience_assessor_assignments (
  assessor_id uuid not null references public.profiles(id) on delete cascade,
  scope_name text not null,
  is_active boolean not null default true,
  assigned_by uuid references public.profiles(id),
  updated_at timestamptz not null default now(),
  primary key (assessor_id, scope_name)
);

create table if not exists public.prior_experience_scope_reviews (
  id bigint generated by default as identity primary key,
  logbook_id bigint not null references public.prior_experience_logbooks(id) on delete cascade,
  scope_name text not null,
  status text not null default 'pending',
  decided_by uuid references public.profiles(id),
  note text,
  decided_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(logbook_id, scope_name),
  constraint prior_experience_scope_status_check check (status in ('pending','approved','rejected'))
);

create table if not exists public.prior_experience_reconsiderations (
  id bigint generated by default as identity primary key,
  logbook_id bigint not null references public.prior_experience_logbooks(id) on delete cascade,
  review_kind text not null,
  review_id bigint not null,
  reviewer_id uuid not null references public.profiles(id),
  scope_name text,
  resident_reason text not null,
  status text not null default 'requested',
  reviewer_note text,
  created_at timestamptz not null default now(),
  resolved_at timestamptz,
  constraint prior_experience_reconsideration_kind_check check (review_kind in ('senior','assessor')),
  constraint prior_experience_reconsideration_status_check check (status in ('requested','approved','rejected'))
);

create unique index if not exists prior_experience_one_pending_reconsideration_idx
  on public.prior_experience_reconsiderations(review_kind, review_id)
  where status = 'requested';

create index if not exists prior_experience_scope_assignment_idx
  on public.prior_experience_assessor_assignments(scope_name, is_active);
create index if not exists prior_experience_scope_reviews_idx
  on public.prior_experience_scope_reviews(logbook_id, status);
create index if not exists prior_experience_senior_reviews_idx
  on public.prior_experience_senior_reviews(logbook_id, status);

alter table public.prior_experience_logbooks enable row level security;
alter table public.prior_experience_interventions enable row level security;
alter table public.prior_experience_conferences enable row level security;
alter table public.prior_experience_senior_reviews enable row level security;
alter table public.prior_experience_assessor_assignments enable row level security;
alter table public.prior_experience_scope_reviews enable row level security;
alter table public.prior_experience_reconsiderations enable row level security;

revoke all on public.prior_experience_logbooks from public, anon, authenticated;
revoke all on public.prior_experience_interventions from public, anon, authenticated;
revoke all on public.prior_experience_conferences from public, anon, authenticated;
revoke all on public.prior_experience_senior_reviews from public, anon, authenticated;
revoke all on public.prior_experience_assessor_assignments from public, anon, authenticated;
revoke all on public.prior_experience_scope_reviews from public, anon, authenticated;
revoke all on public.prior_experience_reconsiderations from public, anon, authenticated;

-- ------------------------------------------------------------------
-- Internal helper: create one assessor-verification scope per activity.
-- ------------------------------------------------------------------
create or replace function public._prior_experience_ensure_scopes_v1068(p_logbook_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row record;
  v_sender uuid;
begin
  select p.id into v_sender
  from public.profiles p
  where p.role::text = 'owner' and p.is_active = true
  order by p.created_at nulls last
  limit 1;

  for v_row in
    with scopes as (
      select distinct i.intervention_name as scope_name
      from public.prior_experience_interventions i
      where i.logbook_id = p_logbook_id
        and (i.attended_count + i.assisted_count + i.solo_guided_count + i.solo_unguided_count) > 0
      union all
      select 'Conferences'
      where exists (select 1 from public.prior_experience_conferences c where c.logbook_id = p_logbook_id)
    )
    insert into public.prior_experience_scope_reviews(logbook_id, scope_name)
    select p_logbook_id, s.scope_name
    from scopes s
    on conflict (logbook_id, scope_name) do nothing
    returning id, scope_name
  loop
    insert into public.private_messages(sender_id, receiver_id, subject, body)
    select coalesce(v_sender, a.assessor_id), a.assessor_id,
           'Prior experience verification request',
           'A resident Prior Experience Logbook is ready for your verification scope: ' || v_row.scope_name || '. Open Logbook requests to review the evidence, comment, approve or reject.'
    from public.prior_experience_assessor_assignments a
    join public.profiles p on p.id = a.assessor_id and p.role::text = 'assessor' and p.is_active = true
    where a.scope_name = v_row.scope_name and a.is_active = true;
  end loop;
end;
$$;
revoke all on function public._prior_experience_ensure_scopes_v1068(bigint) from public, anon, authenticated;

-- --------------------------------------------------------------
-- Internal helper: derive overall status from current decisions.
-- --------------------------------------------------------------
create or replace function public._prior_experience_recalculate_v1068(p_logbook_id bigint)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_senior_total integer;
  v_senior_approved integer;
  v_senior_rejected integer;
  v_scope_total integer;
  v_scope_approved integer;
  v_scope_rejected integer;
  v_status text;
begin
  select count(*), count(*) filter (where status='approved'), count(*) filter (where status='rejected')
    into v_senior_total, v_senior_approved, v_senior_rejected
  from public.prior_experience_senior_reviews
  where logbook_id = p_logbook_id;

  if v_senior_rejected > 0 then
    v_status := 'rejected';
  elsif v_senior_total < 2 or v_senior_approved < 2 then
    v_status := 'senior_review';
  else
    perform public._prior_experience_ensure_scopes_v1068(p_logbook_id);
    select count(*), count(*) filter (where status='approved'), count(*) filter (where status='rejected')
      into v_scope_total, v_scope_approved, v_scope_rejected
    from public.prior_experience_scope_reviews
    where logbook_id = p_logbook_id;

    if v_scope_rejected > 0 then
      v_status := 'rejected';
    elsif v_scope_total = 0 or v_scope_approved < v_scope_total then
      v_status := 'assessor_review';
    else
      v_status := 'approved';
    end if;
  end if;

  update public.prior_experience_logbooks
     set status = v_status,
         verified_at = case when v_status='approved' then coalesce(verified_at, now()) else null end,
         updated_at = now()
   where id = p_logbook_id;

  return v_status;
end;
$$;
revoke all on function public._prior_experience_recalculate_v1068(bigint) from public, anon, authenticated;

-- --------------------------------------------------------------
-- Resident: eligible senior signatories (higher year; Year 5 uses Year 5 peers because no higher cohort exists).
-- --------------------------------------------------------------
create or replace function public.get_prior_experience_eligible_seniors_v1068()
returns table(id uuid, display_name text, residency_year smallint)
language sql
security definer
set search_path = public
as $$
  select s.id, s.display_name, s.residency_year
  from public.profiles me
  join public.profiles s on s.role::text='resident'
    and s.is_active=true
    and s.id<>me.id
    and (s.residency_year > me.residency_year or (me.residency_year=5 and s.residency_year=5))
  where me.id=auth.uid() and me.role::text='resident' and me.is_active=true
  order by s.residency_year, s.display_name;
$$;
revoke all on function public.get_prior_experience_eligible_seniors_v1068() from public, anon;
