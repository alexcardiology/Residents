create or replace function public.owner_set_prior_experience_assessor_scopes_v1068(
  p_assessor_id uuid,
  p_scopes text[]
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_scope text;
  v_count integer := 0;
  v_allowed text[] := array[
    'CVP','Intubation','Temporary pacemaker','Permanent pacemaker implantation','Pacemaker programming',
    'ICD implantation','CRT implantation','Pericardiocentesis','TEE','DSE','Coronary angiography',
    'Elective PCI','Primary PCI','IVUS','Rotablation','TAVI','ASD closure','Mitral balloon valvotomy',
    'Exercise stress ECG','Tilting table','Nuclear imaging','CT CA','CMR','CPR','Conferences'
  ];
begin
  if not exists (select 1 from public.profiles p where p.id=auth.uid() and p.role::text='owner' and p.is_active=true) then raise exception 'Owner access required'; end if;
  if not exists (select 1 from public.profiles p where p.id=p_assessor_id and p.role::text='assessor' and p.is_active=true) then raise exception 'Active assessor not found'; end if;

  update public.prior_experience_assessor_assignments
     set is_active=false, updated_at=now(), assigned_by=auth.uid()
   where assessor_id=p_assessor_id and is_active=true;

  foreach v_scope in array coalesce(p_scopes,array[]::text[])
  loop
    if not (v_scope = any(v_allowed)) then raise exception 'Unsupported assessor scope: %', v_scope; end if;
    insert into public.prior_experience_assessor_assignments(assessor_id,scope_name,is_active,assigned_by,updated_at)
    values (p_assessor_id,v_scope,true,auth.uid(),now())
    on conflict (assessor_id,scope_name) do update set is_active=true, assigned_by=excluded.assigned_by, updated_at=now();
    v_count := v_count + 1;

    -- If there are already waiting scope reviews, notify this newly assigned assessor.
    insert into public.private_messages(sender_id,receiver_id,subject,body)
    select auth.uid(), p_assessor_id, 'Prior experience verification waiting',
           'A Prior Experience Logbook is already waiting for verification in your newly assigned scope: '||v_scope||'. Open Logbook requests.'
    from public.prior_experience_scope_reviews sc
    join public.prior_experience_logbooks l on l.id=sc.logbook_id
    where sc.scope_name=v_scope and sc.status='pending' and l.status in ('assessor_review','rejected')
      and not exists (
        select 1 from public.private_messages pm
        where pm.receiver_id=p_assessor_id and pm.subject='Prior experience verification waiting'
          and pm.body like '%'||v_scope||'%'
          and pm.created_at > now()-interval '1 day'
      )
    limit 1;
  end loop;
  return v_count;
end;
$$;
revoke all on function public.owner_set_prior_experience_assessor_scopes_v1068(uuid,text[]) from public, anon;
grant execute on function public.owner_set_prior_experience_assessor_scopes_v1068(uuid,text[]) to authenticated;

commit;
